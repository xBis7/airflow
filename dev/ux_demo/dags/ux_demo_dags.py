@task
def simulate_work(min_seconds: int, max_seconds: int, failure_permille: int) -> None:
    """Sleep for a while and fail for a stable, pseudo-random subset of task instances."""
    ti = get_current_context()["ti"]
    digest = hashlib.sha256(f"{ti.dag_id}|{ti.task_id}|{ti.run_id}".encode()).digest()
    sleep_roll = int.from_bytes(digest[:4], "big") % 1000
    failure_roll = int.from_bytes(digest[4:8], "big") % 1000
    time.sleep(min_seconds + (max_seconds - min_seconds) * sleep_roll / 1000)
    if failure_roll < failure_permille:
        raise RuntimeError("Simulated failure for the UX demo")


for demo in DEMO_DAGS:
    with DAG(
        dag_id=demo.dag_id,
        schedule=CronTriggerTimetable(demo.cron, timezone="UTC") if demo.cron else None,
        start_date=pendulum.datetime(2022, 1, 1, tz="UTC"),
        catchup=False,
        max_active_runs=3,
        description=demo.description,
        tags=demo.tags,
        default_args={"owner": demo.owner, "retries": 0},
    ):
        previous_stage: list = []
        for stage in demo.stages:
            current_stage = [
                simulate_work.override(task_id=task_id)(
                    demo.min_task_seconds, demo.max_task_seconds, demo.failure_permille
                )
                for task_id in stage
            ]
            for upstream in previous_stage:
                for downstream in current_stage:
                    upstream >> downstream
            previous_stage = current_stage
