    dag_id: str
    cron: str | None
    description: str
    owner: str
    tags: list[str]
    # Every task in a stage depends on every task in the previous stage.
    stages: list[list[str]]
    failure_permille: int = 0
    min_task_seconds: int = MIN_TASK_SECONDS
    max_task_seconds: int = MAX_TASK_SECONDS


